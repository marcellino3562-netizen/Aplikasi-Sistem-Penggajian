    private void TambahData_ButtActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_TambahData_ButtActionPerformed
        // TODO add your handling code here:
        try {
            
            String id = txtId.getText();
            String nama = txtNama.getText();

            
            if (id.isEmpty() || nama.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Mohon lengkapi semua data karyawan!");
                return;
            }

            
            KaryawanController karyawanCtrl = new KaryawanController();
            boolean sukses = karyawanCtrl.tambahKaryawan(id, nama);

            
            if (sukses) {
                javax.swing.JOptionPane.showMessageDialog(this, "Data Karyawan Berhasil Disimpan!");
                txtId.setText("");
                txtNama.setText("");
                tampilkanDataKaryawan();
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Gagal menyimpan data! Cek apakah ID sudah ada.");
            }

        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Terjadi Kesalahan: " + e.getMessage());
        }
    }//GEN-LAST:event_TambahData_ButtActionPerformed

    private void jTable3MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable3MouseClicked
        // TODO add your handling code here:
        
        int baris = jTable3.getSelectedRow();

        
        if (baris != -1) {
            txtId.setText(jTable3.getValueAt(baris, 0).toString());
            txtNama.setText(jTable3.getValueAt(baris, 1).toString());

            
            txtId.setEnabled(false);
        }
    }//GEN-LAST:event_jTable3MouseClicked

    private void EditButtActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_EditButtActionPerformed
        // TODO add your handling code here:
        try {
            String id = txtId.getText();
            String nama = txtNama.getText();

            controller.KaryawanController controller = new controller.KaryawanController();
            boolean sukses = controller.editKaryawan(id, nama);

            if (sukses) {
                javax.swing.JOptionPane.showMessageDialog(this, "Data Karyawan Berhasil Diedit!");
                tampilkanDataKaryawan();

                
                txtId.setText("");
                txtNama.setText("");
                txtId.setEnabled(true);
            }
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Terjadi Kesalahan: " + e.getMessage());
        }
    }//GEN-LAST:event_EditButtActionPerformed

    private void HapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_HapusActionPerformed
        // TODO add your handling code here:
        String id = txtId.getText();

        if (id.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Pilih dulu data yang mau dihapus dari tabel!");
            return;
        }

        int konfirmasi = javax.swing.JOptionPane.showConfirmDialog(this, "Yakin ingin menghapus karyawan dengan ID " + id + "?", "Konfirmasi Hapus", javax.swing.JOptionPane.YES_NO_OPTION);

        if (konfirmasi == javax.swing.JOptionPane.YES_OPTION) {
            controller.KaryawanController controller = new controller.KaryawanController();
            boolean sukses = controller.hapusKaryawan(id);

            if (sukses) {
                javax.swing.JOptionPane.showMessageDialog(this, "Data Berhasil Dihapus!");
                tampilkanDataKaryawan();

                txtId.setText("");
                txtNama.setText("");
                txtId.setEnabled(true);
            }
        }
    }//GEN-LAST:event_HapusActionPerformed

