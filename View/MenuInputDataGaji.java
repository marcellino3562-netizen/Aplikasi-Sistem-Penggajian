    private void SimpanButtActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_SimpanButtActionPerformed
        // TODO add your handling code here:
      
    String idKaryawan = cmbIdKaryawan.getSelectedItem().toString();
    
   
    if (idKaryawan.equals("-- Pilih ID Karyawan --")) {
        javax.swing.JOptionPane.showMessageDialog(this, "Silakan pilih ID Karyawan terlebih dahulu!");
        return; 
    }

    try {
        model.DataGaji data = new model.DataGaji();
        
       
        data.setIdGaji(txtIdGaji.getText());
        data.setIdKaryawan(idKaryawan); 
        data.setGajiPokok(Integer.parseInt(txtGajiPokok.getText()));
        
        int totalKasbon = 0;
        if (!txtKasbon.getText().isEmpty()) {
            totalKasbon = Integer.parseInt(txtKasbon.getText());
        }
        data.setTotalKasbon(totalKasbon);
        data.setGajiBersih(Integer.parseInt(txtGajiBersih.getText()));
        data.setJumlahHadir(Integer.parseInt(txtAbsensi.getText()));
     
        controller.GajiController controllerGaji = new controller.GajiController();

        boolean sukses = controllerGaji.tambahDataGaji(data);
        

        if (sukses) {
            javax.swing.JOptionPane.showMessageDialog(this, "Data Gaji Berhasil Disimpan!");
            cmbIdKaryawan.setSelectedIndex(0); 
            txtIdGaji.setText(controllerGaji.generateIdOtomatis());
            txtGajiPokok.setText("");
            txtKasbon.setText("");
            txtGajiBersih.setText("");
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Gagal menyimpan data. Cek output log.");
        }
        
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Pastikan Anda sudah menekan tombol 'Hitung Gaji' dan semua format angka benar!");
    }
    }//GEN-LAST:event_SimpanButtActionPerformed

