    private void HitungGajiButtActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_HitungGajiButtActionPerformed
        // TODO add your handling code here:
    try {
    int gajiPokok = Integer.parseInt(txtGajiPokok.getText());
    int kasbon = 0;
    if (!txtKasbon.getText().isEmpty()) {
        kasbon = Integer.parseInt(txtKasbon.getText());
    }
    

    int hariMasuk = Integer.parseInt(txtAbsensi.getText());


    int hariKerjaTarget = 26; 
    int hariBolos = hariKerjaTarget - hariMasuk;
    
  
    int potonganAbsensi = 0;
    if (hariBolos > 0) {
        potonganAbsensi = hariBolos * 50000;
    }
    
    int gajiBersih = gajiPokok - potonganAbsensi - kasbon;

    txtGajiBersih.setText(String.valueOf(gajiBersih));

} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(this, "Inputan angka salah, cek lagi ya!");
}
    }//GEN-LAST:event_HitungGajiButtActionPerformed

