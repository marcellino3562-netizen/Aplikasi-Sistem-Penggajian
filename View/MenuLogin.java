    private void MasukButtActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_MasukButtActionPerformed
        // TODO add your handling code here:                                                                                                                     
        
    String username = txtUsername.getText();
    String password = new String(txtPassword.getPassword());

    if (username.isEmpty() || password.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Username dan Password wajib diisi!");
        return;
    }

    try {
        java.sql.Connection conn = Connector.konekkan.configDB();
        
        String sql = "SELECT * FROM user WHERE id_user = ? AND password = ?";
        java.sql.PreparedStatement pst = conn.prepareStatement(sql);
        pst.setString(1, username);
        pst.setString(2, password);
        
        java.sql.ResultSet rs = pst.executeQuery();
        
        if (rs.next()) {
            String userTerdaftar = rs.getString("id_user"); 
            
            if (userTerdaftar.equalsIgnoreCase("Owner")) {
                javax.swing.JOptionPane.showMessageDialog(this, "Login berhasil sebagai Owner!");
                new View.DashboardOwner().setVisible(true);
                this.dispose();
                
            } else if (userTerdaftar.equalsIgnoreCase("Admin")) {
                javax.swing.JOptionPane.showMessageDialog(this, "Login berhasil sebagai Admin!");
                new View.DashboardAdmin().setVisible(true);
                this.dispose();
                
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "ID User tidak dikenali sistem!");
            }
            
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Username atau Password SALAH!");
        }
        
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Koneksi ke Database Gagal: " + e.getMessage());
    }
    }//GEN-LAST:event_MasukButtActionPerformed

