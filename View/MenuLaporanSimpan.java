    private void tampilkanData() {
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);
        
        controller.ManajerLaporan controllerLaporan = new controller.ManajerLaporan();
        java.sql.ResultSet rs = controllerLaporan.getLaporanGaji();
        
        try {
            if (rs != null) {
                while (rs.next()) {
                    String idGaji = rs.getString("Id_gaji");
                    String tanggal = rs.getString("tanggal");
                    String idKaryawan = rs.getString("id_karyawan");
                    int gajiBersih = rs.getInt("gajiBersih");
                    
                    model.addRow(new Object[]{idGaji, tanggal, idKaryawan, gajiBersih});
                }
            }
        } catch (Exception e) {
            System.err.println("Gagal menampilkan data ke tabel: " + e.getMessage());
        }
    }

