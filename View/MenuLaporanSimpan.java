    private void jDateChooser1PropertyChange(java.beans.PropertyChangeEvent evt) {//GEN-FIRST:event_jDateChooser1PropertyChange
        // TODO add your handling code here:
      if ("date".equals(evt.getPropertyName())) {
        try {
            if (jDateChooser1.getDate() != null) {
                java.text.SimpleDateFormat sdf = new java.text.SimpleDateFormat("yyyy-MM-dd");
                String tanggalFormatDB = sdf.format(jDateChooser1.getDate());

                javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) jTable1.getModel();
                model.setRowCount(0); 

                controller.ManajerLaporan manajer = new controller.ManajerLaporan();
                java.util.ArrayList<model.DataLaporan> listLaporan = manajer.getLaporanGajiByTanggal(tanggalFormatDB);

                for (model.DataLaporan data : listLaporan) {
                    model.addRow(new Object[]{
                        data.getIdGaji(), 
                        data.getTanggal(), 
                        data.getIdKaryawan(), 
                        data.getGajiBersih()
                    });
                }
            }
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Terjadi kesalahan: " + e.getMessage());
        }
    }
    }//GEN-LAST:event_jDateChooser1PropertyChange

    private void ButtSlipActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ButtSlipActionPerformed
        // TODO add your handling code here:
       try {
    int row = jTable1.getSelectedRow(); 
    
    if (row == -1) {
        javax.swing.JOptionPane.showMessageDialog(this, "Pilih dulu data gaji di tabel!");
        return;
    }
    
    String idGaji = jTable1.getValueAt(row, 0).toString(); 

    java.sql.Connection conn = Connector.konekkan.configDB();
    java.io.InputStream fileSlip = getClass().getResourceAsStream("/View/SlipGaji.jasper");
    
    java.util.HashMap parameter = new java.util.HashMap();
    parameter.put("idGaji", idGaji);
    
    net.sf.jasperreports.engine.JasperPrint jp = net.sf.jasperreports.engine.JasperFillManager.fillReport(fileSlip, parameter, conn);
    
    net.sf.jasperreports.view.JasperViewer.viewReport(jp, false);
    
} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(this, "Gagal mencetak: " + e.getMessage());
} 
        
    }//GEN-LAST:event_ButtSlipActionPerformed

