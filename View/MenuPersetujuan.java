    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        try {
    
    int row = jTable1.getSelectedRow();
    
    
    if (row == -1) {
        javax.swing.JOptionPane.showMessageDialog(this, "Pilih dulu data gaji yang mau ditolak bossku!");
        return; 
    }
    
    
    String idGajiDipilih = jTable1.getValueAt(row, 0).toString();
    

    int konfirmasi = javax.swing.JOptionPane.showConfirmDialog(this, 
            "Yakin mau menolak "
                    + "pencairan gaji untuk ID " + idGajiDipilih + "?", 
            "Konfirmasi Penolakan", 
            javax.swing.JOptionPane.YES_NO_OPTION);
            

    if (konfirmasi == javax.swing.JOptionPane.YES_OPTION) {

        controller.PersetujuanController pc = new controller.PersetujuanController();
        pc.tolakGaji(idGajiDipilih);
        

       tampilkanDataPending();
    }
    
} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(this, "Terjadi kesalahan: " + e.getMessage());
}
    }//GEN-LAST:event_jButton2ActionPerformed

